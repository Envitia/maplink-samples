#if _MSC_VER > 1000
#pragma once
#endif // _MSC_VER > 1000

class CDOTrack ;

class CTrack : public TSLDynamicDataObject  
{
public:

  CTrack() ;
  CTrack( const CTrack & other );
  virtual ~CTrack();

  virtual void translate( TSLMapDataLayer * pLayer ) ;  // Move the Track, update the headings and history
  void updateCourse() ;				      // Update the displacement and velocity vectors

  ///////////////////////////////////////////////////
  // Get functions - used to draw the display object
  // and to display track information in the 
  // track information view
  virtual HOSTILE_TYPE  hostility()     { return m_hostility ; }
  int	      trackNumber()               { return m_trackNumber ; }
  char const* trackLabel() const        { return m_pTrackLabel; }
  int trackLabelLen() const
  {
    return m_labelLen;
  }

  virtual TRACK_TYPE trackType() const = 0 ;

  double	heading()	{ return m_heading * 180 / PI ; }
  double	velocity()      { return m_velocity ; }
  double	altitude()      { return m_altitude ; }

  void  latitude( char * buffer ) ;    // Return a formatted buffer
  void  longitude( char * buffer ) ;   // containing latitude or longitude

  void  velocityVectorData( long& x, long& y ) ;   
  const vector< pair< long, long > >&   historyPoints() ;

  ///////////////////////////////////////////////////
  // Set functions - altered values from the Track 
  // Info dialog in the information view
  void heading( double heading ) ;
  void velocity( double velocity ) ;
  void altitude( double altitude ) ;
  virtual void hostility( HOSTILE_TYPE hostility ) ;

protected:
  HOSTILE_TYPE  m_hostility ;

  double m_velocity ;	    // Velocity of the track. Generated randomly in the Track Manager
  double m_altitude ;	    // Altitude of the track. Generated randomly in the Track Manager
  double m_velocityMPS ;	    // Velocity in Metres Per Second

  double m_heading ;	    // Current heading of the track
  double m_targetHeading ;    // Next heading of the track

  double m_latitude ;	    // Latitude....
  double m_longitude ;	    // Longitude....

  long m_dx ;		    // Displacement in terms of x for the moving track
  long m_dy ;		    // Displacement in terms of y for the moving track

  long m_velocityVectorX ;    // Used to draw a vector in front of the track to indicate
  long m_velocityVectorY ;    // the heading and magnitude of velocity

  vector<pair<long, long> > m_historyPoints ;	// Used for plotting the tracks
  int			  m_historyCounter ;	// past movements

  int m_trackNumber ;	    // Track ID, generated by call to CTrackManager::getNewTrackID() in constructor

  string m_trackLabel;
  char const* m_pTrackLabel;

  int m_labelLen;

};

#endif // !defined(AFX_TRACK_H__67E4AB82_490B_11D5_BD2D_00104BB05CAE__INCLUDED_)
